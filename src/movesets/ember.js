// Yakumo is a 13-impact cinematic, not 13 damage packets on one collision
// frame. Each entry owns a distinct authored window; hitstop then gives every
// impact enough screen time for the combo counter and health bar to advance.
const YAKUMO_CINEMATIC_GAPS = Object.freeze([2, 2, 2, 1, 1, 1, 1, 2, 1, 1, 2, 3, 0]);
const YAKUMO_CINEMATIC_HITSTOP = Object.freeze([8, 5, 5, 4, 4, 4, 4, 5, 4, 4, 5, 7, 14]);
const YAKUMO_CINEMATIC_PATTERN = Object.freeze(YAKUMO_CINEMATIC_GAPS.map((gapAfter, index) => Object.freeze({
  id: index === 0 ? "hit1" : `scriptedHit${index + 1}`,
  frames: index === 0 || index === YAKUMO_CINEMATIC_GAPS.length - 1 ? 2 : 1,
  ...(gapAfter > 0 ? { gapAfter } : {}),
})));
const YAKUMO_CINEMATIC_HIT_OVERRIDES = Object.freeze(YAKUMO_CINEMATIC_HITSTOP.map((hitstop, index) => Object.freeze({
  hitstop,
  // Keep the captured target in the cinematic until the terminal launch.
  knockback: index === YAKUMO_CINEMATIC_HITSTOP.length - 1 ? 4 : 0,
})));

