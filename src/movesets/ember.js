function command(label, buttons = [], options = {}) {
  return { buttons, label, ...options };
}

function phaseWindows(startup, pattern = [1]) {
  let cursor = startup;
  return pattern.map((entry, index) => {
    const phase = typeof entry === "number" ? { frames: entry } : entry;
    const frames = Math.max(1, Number(phase.frames) || 1);
    const id = String(phase.id ?? `hit${index + 1}`);
    const window = {
      id,
      hitId: String(phase.hitId ?? id),
      start: cursor,
      end: cursor + frames - 1,
    };
    cursor = window.end + 1 + Math.max(0, Number(phase.gapAfter) || 0);
    return window;
  });
}

function normalizeCancelRules(cancel, windows) {
  if (!cancel || cancel.tier === "none") return [];
  const rules = cancel.rules ?? [cancel];
  return rules.map((rule) => {
    const indexes = rule.hitIndexes ?? windows.map((_, index) => index);
    const selected = indexes.map((index) => windows[index]).filter(Boolean);
    const first = selected[0] ?? windows[0];
    const last = selected[selected.length - 1] ?? windows[windows.length - 1];
    return {
      start: rule.start ?? first.start,
      end: rule.end ?? last.end,
      on: rule.on ?? ["hit", "block"],
      into: rule.into ?? CANCEL_TARGETS[rule.tier] ?? [],
      moves: rule.moves ?? [],
      requiresContact: rule.requiresContact !== false,
      delayable: Boolean(rule.delayable),
    };
  });
}

function authoredMove(config) {
  const {
    name,
    command: authoredCommand,
    category = "normal",
    startup,
    pattern = [1],
    recovery,
    damage = 0,
    damageHits = [damage],
    hit = {},
    hitOverrides = [],
    cancel = NO_CANCEL,
    cost = {},
    routeFrom = [],
    routeTo = [],
    knockdown = NO_KNOCKDOWN,
    juggle = NO_JUGGLE,
    tags = [],
    animation,
    dataConfidence = VERIFIED,
    stance = "ground",
    strength = "",
    ...extra
  } = config;
  const activeWindows = phaseWindows(startup, pattern);
  const hitLevel = hit.level ?? "mid";
  const authoredHits = damageHits.map((hitDamage, index) => {
    const window = activeWindows[Math.min(index, activeWindows.length - 1)];
    const override = hitOverrides[index] ?? {};
    const isLast = index === damageHits.length - 1;
    return {
      id: String(override.id ?? (index < activeWindows.length ? window.hitId : `scriptedHit${index + 1}`)),
      start: override.start ?? window.start,
      end: override.end ?? window.end,
      damage: hitDamage,
      hitLevel: override.hitLevel ?? hitLevel,
      knockdownType: override.knockdownType ?? (isLast && knockdown.type !== "none" ? knockdown.type : undefined),
      juggleCost: override.juggleCost ?? (isLast ? juggle.cost : undefined),
      juggleLimit: override.juggleLimit ?? (isLast ? juggle.limit : undefined),
      groundBounces: override.groundBounces ?? (isLast ? knockdown.groundBounces : undefined),
      wallBounces: override.wallBounces ?? (isLast ? knockdown.wallBounces : undefined),
      initialProration: override.initialProration ?? hit.initialProration,
      scalingStep: override.scalingStep ?? hit.scalingStep,
      minimumScaling: override.minimumScaling ?? hit.minimumScaling,
      ...override,
    };
  });

  return {
    ...extra,
    name,
    command: authoredCommand,
    commandLabel: authoredCommand?.label ?? "",
    category,
    startup,
    activeWindows,
    recovery,
    damage,
    damageHits: [...damageHits],
    hit: { level: hitLevel, ...hit },
    hitLevel,
    hits: authoredHits,
    cancel,
    cancels: normalizeCancelRules(cancel, activeWindows),
    cost: { ...cost },
    routeFrom: [...routeFrom],
    routeTo: [...routeTo],
    knockdown: { ...knockdown },
    knockdownType: knockdown.type === "none" ? undefined : knockdown.type,
    groundBounces: knockdown.groundBounces,
    wallBounces: knockdown.wallBounces,
    quickRiseWindow: knockdown.type === "soft" ? 8 : undefined,
    maximumDelayRise: knockdown.type === "soft" ? 18 : undefined,
    juggle: { ...juggle },
    juggleCost: juggle.cost,
    juggleLimit: juggle.limit,
    tags: [...tags],
    animation,
    dataConfidence,
    sourceVersion: "2.51",
    stance,
    strength,
  };
}

